#!/usr/bin/env python3
"""Single source of truth for PS5 / dev-machine addresses.

All tools in tools/ps5/ read their host and port settings from here instead of
hard-coding LAN IPs. Resolution order (highest priority first):

    1. process environment variables           (PS5_HOST=... ./script.py)
    2. <repo>/.env.local                        (private, git-ignored override)
    3. <repo>/.env                              (shared defaults, committed)
    4. <repo>/.env.example                      (last-resort template)

Set PS5_ENV_FILE=/path/to/file to load one specific file instead of 2-4.

Python usage:
    import ps5_env
    ap.add_argument('--host', default=ps5_env.PS5_HOST)

Shell usage:
    eval "$(python3 tools/ps5/ps5_env.py --shell)"
    echo "$PS5_HOST $DEV_SSH"
"""
import os
import shlex
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.abspath(os.path.join(_HERE, '..', '..'))

# key -> default. Documented in .env.example.
_DEFAULTS = {
    'PS5_HOST': '192.168.88.33',
    'PS5_FTP_PORT': '2121',
    'PS5_WFM_PORT': '8888',
    'PS5_TITLE_ID': 'PPSA99201',
    'DEV_HOST': '192.168.88.253',
    'DEV_USER': 'swizard',
    'DEV_CODE_DIR': '/data/code/switchrecomp',
    'DEV_WORK_ROOT': '/data/switchrecomp',
}


def _parse(path):
    """Parse a minimal KEY=VALUE dotenv file. Ignores blanks/# comments,
    optional 'export ' prefix and surrounding quotes. Returns a dict."""
    out = {}
    try:
        with open(path, 'r', encoding='utf-8') as f:
            for raw in f:
                line = raw.strip()
                if not line or line.startswith('#'):
                    continue
                if line.startswith('export '):
                    line = line[7:].lstrip()
                if '=' not in line:
                    continue
                k, v = line.split('=', 1)
                k, v = k.strip(), v.strip()
                # strip an inline comment only when not inside quotes
                if not v.startswith(('"', "'")) and ' #' in v:
                    v = v.split(' #', 1)[0].rstrip()
                if len(v) >= 2 and v[0] == v[-1] and v[0] in ('"', "'"):
                    v = v[1:-1]
                if k:
                    out[k] = v
    except OSError:
        pass
    return out


def env_files():
    explicit = os.environ.get('PS5_ENV_FILE')
    if explicit:
        return [explicit]
    return [os.path.join(_REPO, n) for n in ('.env.local', '.env', '.env.example')]


def load():
    """Return the fully resolved settings dict (env vars win over files)."""
    merged = dict(_DEFAULTS)
    for path in reversed(env_files()):   # lowest priority first
        merged.update(_parse(path))
    for k in list(merged):
        if k in os.environ and os.environ[k] != '':
            merged[k] = os.environ[k]
    # derived values
    merged['DEV_SSH'] = '%s@%s' % (merged['DEV_USER'], merged['DEV_HOST'])
    merged['PS5_FTP_DIR'] = '/mnt/usb1/%s' % merged['PS5_TITLE_ID']
    return merged


_CFG = load()

PS5_HOST = _CFG['PS5_HOST']
PS5_FTP_PORT = int(_CFG['PS5_FTP_PORT'])
PS5_WFM_PORT = int(_CFG['PS5_WFM_PORT'])
PS5_TITLE_ID = _CFG['PS5_TITLE_ID']
DEV_HOST = _CFG['DEV_HOST']
DEV_USER = _CFG['DEV_USER']
DEV_SSH = _CFG['DEV_SSH']
DEV_CODE_DIR = _CFG['DEV_CODE_DIR']
DEV_WORK_ROOT = _CFG['DEV_WORK_ROOT']
PS5_FTP_DIR = _CFG['PS5_FTP_DIR']


def shell_exports():
    lines = ['# generated by ps5_env.py --shell (eval this)']
    for k in sorted(_CFG):
        lines.append('%s=%s' % (k, shlex.quote(str(_CFG[k]))))
    return '\n'.join(lines) + '\n'


def main():
    if '--shell' in sys.argv:
        sys.stdout.write(shell_exports())
        return 0
    if '--show' in sys.argv:
        print('# env files (highest priority first):')
        for p in env_files():
            print('#   %s %s' % (p, '(present)' if os.path.isfile(p) else '(absent)'))
        for k in sorted(_CFG):
            print('%s=%s' % (k, _CFG[k]))
        return 0
    key = sys.argv[1] if len(sys.argv) > 1 else None
    if key:
        print(_CFG.get(key, ''))
        return 0
    sys.stdout.write(shell_exports())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
